// Release signing is opt-in via a local, gitignored keystore/keystore.properties -- absent on
// CI/other machines without it, `release` simply builds unsigned rather than failing the build.
val keystorePropertiesFile = rootProject.file("keystore/keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

android {
    namespace = "com.astrocompass"
    compileSdk = libs.versions.android.compileSdk.get().toInt()

    // Lets androidUnitTest read the real committed catalog blobs off the classpath (as
    // java.io.File-backed resources) instead of via Compose's Res.readBytes, which needs
    // android.util.Log and isn't available to a plain (non-Robolectric) JVM unit test.
    sourceSets.getByName("test") {
        resources.srcDir("src/commonMain/composeResources/files")
    }

    defaultConfig {
        applicationId = "com.astrocompass"
        minSdk = libs.versions.android.minSdk.get().toInt()
        targetSdk = libs.versions.android.targetSdk.get().toInt()
        versionCode = 6
        versionName = "2.2.0-beta"
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                storeFile = rootProject.file("keystore/${keystoreProperties["storeFile"]}")
                storePassword = keystoreProperties["storePassword"] as String
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
            }
        }
    }
    buildTypes {
        getByName("release") {
            isMinifyEnabled = false
            if (keystorePropertiesFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
}

